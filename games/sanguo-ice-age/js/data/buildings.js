export function buildingCost(def, level) {
  if (def.costTiers) {
    const tier = def.costTiers[level];
    return tier ? { ...tier } : null;
  }
  if (level >= def.maxLevel) return null;
  const out = {};
  for (const [res, base] of Object.entries(def.baseCost)) {
    if (base <= 0) continue;
    out[res] = Math.round(base * Math.pow(def.costGrowth, level));
  }
  return out;
}
