/**
 * 生成图标元素。
 * @param {string} name  图标名
 * @param {string} [cls] 附加 class
 */
export function icon(name, cls = '') {
  const d = STROKE[name];
  if (d) {
    return fromHTML(
      `<svg class="icon ${cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor"
            stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round"
            aria-hidden="true" focusable="false"><path d="${d}"/></svg>`
    );
  }
  const f = FILL[name];
  return fromHTML(
    `<svg class="icon ${cls}" viewBox="0 0 24 24" fill="currentColor" aria-hidden="true"
          focusable="false"><path d="${f || FILL.dot}"/></svg>`
  );
}

/** 按兵器 type 取图标名 */
export function weaponIcon(type) {
  return WEAPON_TYPE_ICON[type] || 'sword';
}
